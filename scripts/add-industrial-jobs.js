function sanitize(obj) {
  if (obj === null || obj === undefined) return null;
  if (Array.isArray(obj)) return obj.map(sanitize);
  if (typeof obj === 'object') {
    const clean = {};
    for (const [k, v] of Object.entries(obj)) {
      if (v !== undefined) {
        clean[k] = sanitize(v);
      }
    }
    return clean;
  }
  return obj;
}

async function uploadToFirestore() {
  const chunkSize = 200;
  for (let i = 0; i < combinedJobs.length; i += chunkSize) {
    const chunk = combinedJobs.slice(i, i + chunkSize);
    const batch = db.batch();

    chunk.forEach((job) => {
      const docRef = db.collection('jobs').doc(job.id);
      batch.set(docRef, sanitize(job), { merge: true });
    });

    console.log(`Mengunggah batch Firestore ${i + 1} s.d. ${Math.min(i + chunkSize, combinedJobs.length)}...`);
    await batch.commit();
  }

  // Simpan metadata
  await db.collection('app_settings').doc('jobs_sync').set(sanitize(updatedMetadata), { merge: true });
  console.log(`\nBERHASIL! ${combinedJobs.length} lowongan kini aktif di Cloud Firestore [katalog-solo-technopark].`);
}

uploadToFirestore()
